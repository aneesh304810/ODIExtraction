CREATE TABLE PBDWAPP.FACT_HOLDINGS (ACCT VARCHAR2(20), SEC VARCHAR2(20), QTY NUMBER(20,4), AS_OF_DT DATE,
  CONSTRAINT PK_FH PRIMARY KEY (ACCT, SEC, AS_OF_DT),
  CONSTRAINT FK_FH_ACCT FOREIGN KEY (ACCT) REFERENCES PBDWAPP.DIM_ACCOUNT(ACCT)) PARTITION BY RANGE (AS_OF_DT) (PARTITION P0 VALUES LESS THAN (MAXVALUE)) TABLESPACE PBDW_DATA;
